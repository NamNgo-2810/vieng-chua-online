/**
 * Minimal CSV helpers for the local history files (SERVER ONLY, pure).
 * Fields are quoted when needed, and text that a spreadsheet would run as a
 * formula (=, +, -, @ at the start) is prefixed with ' so opening the file in
 * Excel or Sheets can never execute something a visitor typed as their name.
 */

/** Escape one field for CSV. */
export function csvField(value: string | number): string {
  let s = String(value);
  if (/^[=+\-@\t\r]/.test(s)) s = `'${s}`;
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

/** One CSV line (no trailing newline). */
export function csvLine(fields: (string | number)[]): string {
  return fields.map(csvField).join(",");
}

/** Parse CSV text into rows of fields (handles quotes, escaped quotes, CRLF). */
export function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++; }
      else if (c === '"') quoted = false;
      else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ",") { row.push(field); field = ""; }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field); rows.push(row); row = []; field = "";
    } else field += c;
  }
  if (field !== "" || row.length) { row.push(field); rows.push(row); }
  return rows;
}
